// Build-time security hardening (see SECURITY.md).
// - Injects a strict Content-Security-Policy <meta> into index.html, allowing the one inline
//   <style> (boot splash) by its SHA-256 hash instead of 'unsafe-inline'.
// - Writes the same headers for every host from one list of rules:
//     dist/_headers  (Cloudflare Pages / Netlify, generated each build)
//     vercel.json    (Vercel reads it from the repo root *before* building, so it is committed;
//                     a local build refreshes it, a build on Vercel/CI fails if it is stale)
// - Writes dist/robots.txt so search engines do not index the app.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

const sha256 = (s: string) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`;

/** Only our own origin may provide code, styles, fonts, images and network connections. */
export function contentSecurityPolicy(styleHashes: string[], asHeader: boolean): string {
  return [
    "default-src 'self'",
    "script-src 'self'", // no inline scripts, no eval, no third-party scripts
    `style-src 'self' ${styleHashes.join(' ')}`.trim(),
    "img-src 'self'",
    "font-src 'self'",
    "connect-src 'self'", // injected code could not send data to another server
    "manifest-src 'self'",
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    ...(asHeader ? ["frame-ancestors 'none'", 'upgrade-insecure-requests'] : []), // ignored in <meta>
  ].join('; ');
}

type Rule = { path: string; headers: [string, string][] };

export function headerRules(styleHashes: string[]): Rule[] {
  const noCache: [string, string][] = [['Cache-Control', 'no-cache']];
  return [
    {
      path: '/*',
      headers: [
        ['Content-Security-Policy', contentSecurityPolicy(styleHashes, true)],
        ['Strict-Transport-Security', 'max-age=63072000; includeSubDomains'],
        ['X-Content-Type-Options', 'nosniff'],
        ['X-Frame-Options', 'DENY'],
        ['Referrer-Policy', 'no-referrer'],
        [
          'Permissions-Policy',
          'accelerometer=(), autoplay=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), midi=(), payment=(), usb=(), browsing-topics=()',
        ],
        ['Cross-Origin-Opener-Policy', 'same-origin'],
        ['Cross-Origin-Resource-Policy', 'same-origin'],
        ['X-Robots-Tag', 'noindex, nofollow'],
      ],
    },
    // updates (and security fixes) must reach the phone right away; hashed assets can be cached forever
    { path: '/', headers: noCache },
    { path: '/index.html', headers: noCache },
    { path: '/sw.js', headers: noCache },
    { path: '/manifest.webmanifest', headers: noCache },
    { path: '/assets/*', headers: [['Cache-Control', 'public, max-age=31536000, immutable']] },
  ];
}

/** Cloudflare Pages / Netlify `_headers` format. */
export function headersFile(styleHashes: string[]): string {
  const blocks = headerRules(styleHashes).map((r) => `${r.path}\n${r.headers.map(([k, v]) => `  ${k}: ${v}`).join('\n')}`);
  return `# Generated by vite.security.ts at build time. Do not edit by hand.\n${blocks.join('\n\n')}\n`;
}

/** Vercel `vercel.json` with the same rules ("/*" becomes the path-to-regexp "/(.*)"). */
export function vercelJson(styleHashes: string[]): string {
  const config = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    framework: 'vite',
    buildCommand: 'npm run build',
    outputDirectory: 'dist',
    headers: headerRules(styleHashes).map((r) => ({
      source: r.path.replace(/\*$/, '(.*)'),
      headers: r.headers.map(([key, value]) => ({ key, value })),
    })),
  };
  return JSON.stringify(config, null, 2) + '\n';
}

export function securityHeaders(): Plugin {
  let root = process.cwd();
  let outDir = 'dist';
  let styleHashes: string[] = [];
  return {
    name: 'kantong-security-headers',
    apply: 'build',
    configResolved(config) {
      root = config.root;
      outDir = path.resolve(config.root, config.build.outDir);
    },
    transformIndexHtml: {
      order: 'post',
      handler(html) {
        if (/<script(?![^>]*\bsrc=)[^>]*>/i.test(html)) throw new Error('index.html contains an inline <script>; the CSP forbids it.');
        styleHashes = [...html.matchAll(/<style>([\s\S]*?)<\/style>/gi)].map((m) => sha256(m[1]));
        const meta = `<meta http-equiv="Content-Security-Policy" content="${contentSecurityPolicy(styleHashes, false)}" />`;
        return html.replace(/<meta charset="UTF-8" \/>/i, (m) => `${m}\n    ${meta}`);
      },
    },
    closeBundle() {
      fs.writeFileSync(path.join(outDir, '_headers'), headersFile(styleHashes));
      fs.writeFileSync(path.join(outDir, 'robots.txt'), 'User-agent: *\nDisallow: /\n');

      const vercelPath = path.join(root, 'vercel.json');
      const expected = vercelJson(styleHashes);
      const current = fs.existsSync(vercelPath) ? fs.readFileSync(vercelPath, 'utf8') : '';
      if (current === expected) return;
      if (process.env.CI || process.env.VERCEL) {
        // On Vercel the headers were already read from the committed file: a stale one would ship a wrong CSP.
        throw new Error('vercel.json is out of date with the build. Run `npm run build` locally and commit vercel.json.');
      }
      fs.writeFileSync(vercelPath, expected);
      console.log('\n[security] vercel.json updated: commit it so Vercel serves the same headers.');
    },
  };
}
